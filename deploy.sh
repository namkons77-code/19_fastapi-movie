#!/bin/bash
set -e

# ==========================================
# CINEFLIX / TVING 프로젝트 원클릭 배포 스크립트
# ==========================================

echo "=========================================="
echo "🚀 [1/5] 최신 소스코드 동기화 (Git Pull)..."
echo "=========================================="
git fetch origin
git pull origin main || git pull origin master

echo ""
echo "=========================================="
echo "🔑 [2/5] 환경변수 (.env) 파일 확인..."
echo "=========================================="
if [ ! -f .env ]; then
    echo "⚠️  .env 파일이 없습니다. .env.example을 기반으로 생성해주세요."
    if [ -f .env.example ]; then
        cp .env.example .env
        echo "ℹ️  .env.example을 .env로 복사했습니다. TMDB 키를 입력해주세요: nano .env"
    fi
    exit 1
fi
echo "✅ .env 파일이 확인되었습니다."

echo ""
echo "=========================================="
echo "🐳 [3/5] Docker 컨테이너 빌드 및 무중단 배포..."
echo "=========================================="
# 최신 코드 기반으로 백그라운드 빌드 & 배포
docker compose up -d --build

echo ""
echo "=========================================="
echo "🧹 [4/5] 이전 버전 불필요한 이미지 정리..."
echo "=========================================="
docker image prune -f

echo ""
echo "=========================================="
echo "🔍 [5/5] 컨테이너 가동 상태 확인..."
echo "=========================================="
docker compose ps

echo ""
echo "🎉 배포가 성공적으로 완료되었습니다!"
echo "👉 웹 브라우저에서 서버의 공인 IP (포트 80)로 접속해보세요."
